#!/usr/bin/env python3
"""Split the unnamed globals (D_<ADDR> data symbols used in C code) into naming chunks (docs/names/PROPOSING.md).

Writes docs/names/globals.tsv: chunk, symbol, home file (the .c file using it most, a header only when no .c does),
number of files using it, number of uses. Symbols below 0x10000000 are ROM offsets / numbers (vbe.py ROM_ABS) and are
left out, and so are symbols only declared in a header (conker/include/variables.h) that no C file uses. Chunks follow the home files in order, about --size symbols each, never splitting a file.
Usage: tools/eu_port/globals_chunks.py [--size 300]"""
import collections, re, subprocess, sys

size = int(sys.argv[sys.argv.index('--size') + 1]) if '--size' in sys.argv else 300
CMT = re.compile(r'/\*.*?\*/|//[^\n]*|"(?:[^"\\\n]|\\.)*"', re.S)
files = [f for f in subprocess.run(['git', 'ls-files', 'conker/src_eu', 'conker/include', 'port'], capture_output=True,
                                   text=True, check=True).stdout.split() if f.endswith(('.c', '.h', '.inc'))]
use = collections.defaultdict(collections.Counter)
for f in files:
    for m in re.findall(r'\bD_[0-9A-F]{8}\b', CMT.sub(' ', open(f, errors='replace').read())):
        if int(m[2:], 16) >= 0x10000000:
            use[m][f] += 1
home = {}
for s, c in list(use.items()):
    cs = {f: k for f, k in c.items() if f.endswith('.c')}
    if not cs:          # only declared in a header, used by no C file: nothing to name it after (left out)
        del use[s]; continue
    home[s] = max(cs.items(), key=lambda kv: (kv[1], kv[0]))[0]
byfile = collections.defaultdict(list)
for s in sorted(use):
    byfile[home[s]].append(s)
rows, chunk, n = [], 1, 0
for f in sorted(byfile):
    if n and n + len(byfile[f]) > size:
        chunk, n = chunk + 1, 0
    for s in byfile[f]:
        rows.append('g%02d\t%s\t%s\t%d\t%d' % (chunk, s, f, len(use[s]), sum(use[s].values())))
    n += len(byfile[f])
with open('docs/names/globals.tsv', 'w') as o:
    o.write('# GENERATED by tools/eu_port/globals_chunks.py: unnamed globals used in C, by naming chunk\n')
    o.write('chunk\tsymbol\thome\tfiles\tuses\n' + '\n'.join(rows) + '\n')
print('%d globals in %d chunks' % (len(rows), chunk))
