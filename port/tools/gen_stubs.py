#!/usr/bin/env python3
"""Generate weak stubs for every symbol the wasm32 game build references but nothing defines.

usage: gen_stubs.py OUTDIR LIBDIR obj.o...   (inside the emsdk container, from the repo root)

Reads the wasm objects' symbol tables (port/tools/wasmobj.py):
  * undefined function -> weak stub with the exact wasm signature seen at the call sites
                          (logs its name once via port_stub_hit(), returns 0)
  * undefined data     -> zeroed array, sized from the N64 address gap to the next known symbol
Symbols provided by emscripten's libc / compiler-rt are left alone.

Writes OUTDIR/asm_stubs.c, OUTDIR/data_stubs.c and OUTDIR/stubs_report.txt.
"""
import os, re, sys, glob, subprocess, collections
sys.path.insert(0, os.path.dirname(__file__))
import wasmobj
import n64mem

CT = {'i32': 'int', 'i64': 'long long', 'f32': 'float', 'f64': 'double'}
SRC = 'conker/src_eu'


def asm_only():
    """name -> file (under conker/src_eu) for every function with no C body (platform-replaced asm). P329: from the frozen
    port/symbols/global_asm.tsv (asm_only = 1); before, from the `#pragma GLOBAL_ASM` lines outside the NON_MATCHING
    #else halves, which the cleanup stripped (same names and files)."""
    return {n: f for n, (f, ao) in n64mem.portsyms.global_asm().items() if ao}


def addresses():
    """name -> link value (address, or the number of an absolute symbol). P328: from the frozen port symbol table
    (port/symbols/symbols.tsv, rows with a link position) instead of the matching build's undefined_*_auto.txt +
    undefined_syms.eu.txt + symbol_addrs.eu.txt (same names, values and order)."""
    return n64mem.portsyms.link_addresses()


def lib_defined(libdir):
    out = set()
    for lib in ('libc.a', 'libcompiler_rt.a', 'libemmalloc.a', 'libstubs.a', 'libc++abi.a'):
        p = os.path.join(libdir, lib)
        if not os.path.exists(p):
            continue
        r = subprocess.run([os.environ.get('LLVM_NM', '/emsdk/upstream/bin/llvm-nm'), '--defined-only', '-j', p], capture_output=True, text=True)
        out.update(x for x in r.stdout.split() if x and not x.endswith(':'))
    return out


def main():
    outdir, libdir, objs = sys.argv[1], sys.argv[2], sys.argv[3:]
    defined, undef_f, undef_d = set(), collections.defaultdict(collections.Counter), set()
    defined_f, defined_d = {}, set()
    for o in objs:
        runtime = '/ultra/' in o  # PC runtime: its definitions count, its imports (emscripten/GL) do not
        for nm, kind, flags, sig in wasmobj.read(o):
            if nm is None or flags & wasmobj.LOCAL:
                continue
            if flags & wasmobj.UNDEF:
                if runtime:
                    continue
                if kind == wasmobj.SYM_FUNC:
                    undef_f[nm][sig] += 1
                elif kind == wasmobj.SYM_DATA:
                    undef_d.add(nm)
            elif kind in (wasmobj.SYM_FUNC, wasmobj.SYM_DATA):
                defined.add(nm)
                if kind == wasmobj.SYM_FUNC:
                    defined_f.setdefault(nm, sig)
                else:
                    defined_d.add(nm)
    libs = lib_defined(libdir)
    asm = asm_only()
    addr = addresses()
    # JS-library imports (WebGL, emscripten html5) and the PC icall runtime are not game functions
    js = ('gl', 'emscripten_', '__port_')
    funcs = sorted(n for n in undef_f if n not in defined and n not in libs and not n.startswith(js))
    # sorted by the original D_ name, so renaming a global does not reorder the zeroed stubs (same wasm layout)
    datas = sorted((n for n in undef_d if n not in defined and n not in libs and not n.startswith('n64_')),
                   key=lambda n: n64mem.RENAMED_FROM.get(n, n))  # mirrors: n64mem_labels.s

    # ---- N64 memory model: mirror labels, relocations, function table (port/tools/n64mem.py)
    stub_sig = {n: undef_f[n].most_common(1)[0][0] for n in funcs}
    extra, mirrored = n64mem.generate(outdir, defined_f, defined_d, stub_sig, datas, addr)
    for n, sig in extra.items():
        undef_f[n][sig] += 1
    funcs = sorted(set(funcs) | set(extra))
    datas = [n for n in datas if n not in mirrored]

    # ---- function stubs
    cat = collections.Counter(); conflicts = []
    L = ['/* GENERATED by port/tools/gen_stubs.py - do not edit. Weak stubs for functions with no C body. */',
         'void port_stub_hit(const char *name, const char *what);', 'int port_stub_dlret(int a0);', 'int port_stub_pt(int a0);', '']
    # P11: pass-through stubs. A still-asm function only ever called as `x = f(x, ...)` (the display-list
    # builders: GDL = func_X(GDL, ...)) returns its first argument instead of 0, so the caller's DL
    # pointer stays valid and the frame still reaches gDPFullSync/gSPEndDisplayList and the gfx task.
    import glob, re
    pt_re = re.compile(r'([A-Za-z_][\w\[\]\.>-]*)\s*=\s*(?:\([^()]*\)\s*)?([A-Za-z_]\w*)\(\s*(?:\([^()]*\)\s*)?([A-Za-z_][\w\[\]\.>-]*)\s*[,)]')
    # P23: also any function declared (prototype or definition) as `Gfx *f(Gfx *, ...)`, e.g. one only
    # used as `return f(gdl, ...)` (player_view_dl_build in render_player_frame_setup).
    gfx_re = re.compile(r'\bGfx\s*\*\s*([A-Za-z_]\w*)\s*\(\s*Gfx\s*\*')
    passthru = set(); passthru_k = {}
    gfx_any_re = re.compile(r'\bGfx\s*\*\s*([A-Za-z_]\w*)\s*\(([^()]*)\)')
    for src in glob.glob('conker/src_eu/**/*.c', recursive=True):
        text = open(src, errors='replace').read()
        for m in pt_re.finditer(text):
            if m.group(1) == m.group(3):
                passthru.add(m.group(2))
        passthru.update(gfx_re.findall(text))
        # P29: `Gfx *f(T, Gfx *, ...)`: the DL pointer is not the first argument (level_dl_visibility_filter in the now-C
        # player_view_dl_build takes it as a1), so the stub returns that argument instead of 0 / a0.
        for m in gfx_any_re.finditer(text):
            parms = [x.strip() for x in m.group(2).split(',')]
            k = next((i for i, x in enumerate(parms) if re.match(r'Gfx\s*\*', x)), None)
            if k: passthru_k[m.group(1)] = k
    # address -> the name its C body is defined under (func_<ADDR>, or its new name after a names.tsv rename, P322)
    by_addr = {}
    for nm_, a_ in addr.items():
        if nm_ in defined_f and defined_f[nm_]:
            by_addr.setdefault(a_, nm_)
    npass = ndl = 0
    # P199: name -> (index of the DL argument, argument count); checked against the asm (returns v0 = that argument)
    # P212: foot_trail_draw (foot-trail / ripple draw, g_fxrec_step_fns table, v0 = a1) removed: C since port P204
    DL_INDIRECT = {}
    for n in funcs:
        sigs = undef_f[n]
        (ps, rs), _ = sigs.most_common(1)[0]
        if len(sigs) > 1:
            conflicts.append((n, len(sigs)))
        what = ('asm:' + asm[n]) if n in asm else ('absolute' if n in addr else 'missing')
        ret = CT.get(rs[0], 'int') if rs else 'void'
        args = ', '.join(f'{CT.get(t, "int")} a{i}' for i, t in enumerate(ps)) or 'void'
        body = f'port_stub_hit("{n}", "{what}");' + ('' if ret == 'void' else ' return 0;')
        if n in DL_INDIRECT and what.startswith('asm'):
            # P199: DL builders reached only through data tables (no C call shape to scan): explicit signature,
            # the stub returns the DL argument instead of 0 (else the caller keeps building at address 0)
            k, nargs = DL_INDIRECT[n]
            ret = 'int'; args = ', '.join(f'int a{i}' for i in range(nargs))
            body = f'port_stub_hit("{n}", "{what}:passthru{k}"); port_stub_dlret(a{k}); return a{k};'
            npass += 1
        if n in passthru_k and n not in passthru and len(ps) > passthru_k[n] and ret != 'void' and what.startswith('asm'):
            k = passthru_k[n]
            body = f'port_stub_hit("{n}", "{what}:passthru{k}"); port_stub_dlret((int)a{k}); return ({ret})a{k};'
            npass += 1
        elif n in passthru and ps and ret != 'void' and what.startswith('asm'):
            body = (f'port_stub_hit("{n}", "{what}:passthru"); return port_stub_pt(a0);' if ret == 'int' and CT.get(ps[0], 'int') == 'int'
                    else f'port_stub_hit("{n}", "{what}:passthru"); return ({ret})a0;')
            npass += 1
        elif ps and ret == 'int' and CT.get(ps[0], 'int') == 'int' and what.startswith('asm'):
            # P23: an int-returning stub whose first argument points into the frame DL buffers is a DL
            # builder called through a shape the source scan misses (`f(g(x))`, `t = f(x); y = h(t)`):
            # port_stub_dlret (pc_os.c) returns a0 then, 0 otherwise.
            body = f'port_stub_hit("{n}", "{what}"); return port_stub_dlret(a0);'
            ndl += 1
        # an "absolute" name (e.g. a US name in undefined_syms.eu.txt = EU address) whose address is a
        # function with a C body under its EU name: forward to it instead of stubbing
        real = by_addr.get(addr[n], f'func_{addr[n]:08X}') if what == 'absolute' else None
        if real and real in defined_f and real != n and defined_f[real]:
            rp, rr = defined_f[real]
            fwd_ret = CT.get(rr[0], 'int') if rr else 'void'
            L.append(f'{fwd_ret} {real}({", ".join(CT.get(t, "int") for t in rp) or "void"});')
            call = f'{real}({", ".join(f"a{i}" if i < len(ps) else "0" for i in range(len(rp)))})'
            body = (f'{call};' if ret == 'void' else (f'return {call};' if fwd_ret != 'void' else f'{call}; return 0;'))
            what = 'alias:' + real
        elif real and real in asm:
            what = f'absolute={real}:asm:{asm[real]}'
        cat[what.split(':')[0].split('=')[0]] += 1
        L.append(f'__attribute__((weak)) {ret} {n}({args}) {{ {body} }}')
    open(f'{outdir}/asm_stubs.c', 'w').write('\n'.join(L) + '\n')
    print(f'pass-through stubs (x = f(x, ...)): {npass}; DL-range pass-through stubs: {ndl}')

    # ---- data stubs: arrays sized by the gap to the next known N64 symbol address
    known = sorted(set(v for v in addr.values() if v >= 0x80000000))
    import bisect
    D = ['/* GENERATED by port/tools/gen_stubs.py - do not edit. Zeroed storage for data symbols that live in',
         ' * ROM blobs / absolute addresses on the N64 (Phase 2b will replace these with real data). */', '']
    lowabs = []
    total = 0
    for n in datas:
        a = addr.get(n)
        if a is None:
            m = re.match(r'D_([0-9A-F]{8})$', n64mem.RENAMED_FROM.get(n, n))   # a renamed D_ global keeps its address
            a = int(m[1], 16) if m else None
        size = 0x100
        if a is not None and a >= 0x80000000:
            i = bisect.bisect_right(known, a)
            size = (known[i] - a) if i < len(known) else 0x1000
            size = max(16, min(size, 0x100000))
        elif a is not None:
            lowabs.append((n, a))
        size = (size + 15) & ~15
        total += size
        D.append(f'__attribute__((weak, aligned(16))) unsigned char {n}[0x{size:X}];'
                 + (f' /* N64 0x{a:08X} */' if a is not None else ''))
    open(f'{outdir}/data_stubs.c', 'w').write('\n'.join(D) + '\n')

    with open(f'{outdir}/stubs_report.txt', 'w') as f:
        f.write(f'function stubs: {len(funcs)}  ' + ', '.join(f'{k}={v}' for k, v in cat.most_common()) + '\n')
        f.write(f'GLOBAL_ASM functions (asm-only) in source: {len(asm)}\n')
        f.write(f'data stubs: {len(datas)}  ({total/1048576:.1f} MB zeroed)\n')
        f.write(f'functions imported with conflicting signatures across TUs: {len(conflicts)}\n')
        for n, k in conflicts:
            sig = '; '.join(f'{",".join(p) or "void"}->{",".join(r) or "void"} x{c}' for (p, r), c in undef_f[n].items())
            f.write(f'  {n}: {sig}\n')
        f.write(f'data symbols with an absolute value below 0x80000000 (ROM offsets / sizes used as &sym): {len(lowabs)}\n')
        for n, a in lowabs[:40]:
            f.write(f'  {n} = 0x{a:X}\n')
    print(open(f'{outdir}/stubs_report.txt').read().split('\n', 4)[:4])


if __name__ == '__main__':
    main()
