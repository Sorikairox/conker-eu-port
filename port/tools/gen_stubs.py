#!/usr/bin/env python3
"""Generate weak stubs for every symbol the wasm32 game build references but nothing defines.

usage: gen_stubs.py OUTDIR LIBDIR obj.o...   (inside the emsdk container, from the repo root)

Reads the wasm objects' symbol tables (port/tools/wasmobj.py):
  * undefined function -> weak stub with the exact wasm signature seen at the call sites
                          (logs its name once via port_stub_hit(), returns 0)
  * undefined data     -> zeroed array, sized from the N64 address gap to the next known symbol
Symbols provided by emscripten's libc / compiler-rt are left alone.

Writes OUTDIR/asm_stubs.c, OUTDIR/data_stubs.c and OUTDIR/stubs_report.txt.
"""
import os, re, sys, glob, subprocess, collections
sys.path.insert(0, os.path.dirname(__file__))
import wasmobj

CT = {'i32': 'int', 'i64': 'long long', 'f32': 'float', 'f64': 'double'}
SRC = 'conker/src_eu'


def asm_only():
    """name -> file for every GLOBAL_ASM function that has no C body in NON_MATCHING mode."""
    res = {}
    for path in glob.glob(f'{SRC}/**/*.c', recursive=True):
        stack = []  # for #ifdef NON_MATCHING ... #else tracking
        for line in open(path, errors='replace'):
            s = line.strip()
            if s.startswith('#if'):
                stack.append('nm' if re.match(r'#ifdef\s+NON_MATCHING\b', s) else
                             'nnm' if re.match(r'#ifndef\s+NON_MATCHING\b', s) else 'other')
            elif s.startswith('#else') and stack:
                stack[-1] = {'nm': 'nm_else', 'nnm': 'nnm_else'}.get(stack[-1], stack[-1])
            elif s.startswith('#endif') and stack:
                stack.pop()
            m = re.match(r'#pragma\s+GLOBAL_ASM\("([^"]+)"\)', s)
            if m and not any(x in ('nm_else', 'nnm') for x in stack):
                res[os.path.splitext(os.path.basename(m[1]))[0]] = os.path.relpath(path, SRC)
    return res


def addresses():
    addr = {}
    for f in ('conker/undefined_syms_auto.txt', 'conker/undefined_funcs_auto.txt',
              'conker/undefined_syms.eu.txt', 'conker/symbol_addrs.eu.txt'):
        for line in open(f):
            m = re.match(r'\s*(\w+)\s*=\s*(0x[0-9A-Fa-f]+|\d+)', line)
            if m:
                addr[m[1]] = int(m[2], 0)
    return addr


def lib_defined(libdir):
    out = set()
    for lib in ('libc.a', 'libcompiler_rt.a', 'libemmalloc.a', 'libstubs.a', 'libc++abi.a'):
        p = os.path.join(libdir, lib)
        if not os.path.exists(p):
            continue
        r = subprocess.run([os.environ.get('LLVM_NM', '/emsdk/upstream/bin/llvm-nm'), '--defined-only', '-j', p], capture_output=True, text=True)
        out.update(x for x in r.stdout.split() if x and not x.endswith(':'))
    return out


def main():
    outdir, libdir, objs = sys.argv[1], sys.argv[2], sys.argv[3:]
    defined, undef_f, undef_d = set(), collections.defaultdict(collections.Counter), set()
    for o in objs:
        runtime = '/ultra/' in o  # PC runtime: its definitions count, its imports (emscripten/GL) do not
        for nm, kind, flags, sig in wasmobj.read(o):
            if nm is None or flags & wasmobj.LOCAL:
                continue
            if flags & wasmobj.UNDEF:
                if runtime:
                    continue
                if kind == wasmobj.SYM_FUNC:
                    undef_f[nm][sig] += 1
                elif kind == wasmobj.SYM_DATA:
                    undef_d.add(nm)
            elif kind in (wasmobj.SYM_FUNC, wasmobj.SYM_DATA):
                defined.add(nm)
    libs = lib_defined(libdir)
    asm = asm_only()
    addr = addresses()
    funcs = sorted(n for n in undef_f if n not in defined and n not in libs)
    datas = sorted(n for n in undef_d if n not in defined and n not in libs)

    # ---- function stubs
    cat = collections.Counter(); conflicts = []
    L = ['/* GENERATED by port/tools/gen_stubs.py - do not edit. Weak stubs for functions with no C body. */',
         'void port_stub_hit(const char *name, const char *what);', '']
    for n in funcs:
        sigs = undef_f[n]
        (ps, rs), _ = sigs.most_common(1)[0]
        if len(sigs) > 1:
            conflicts.append((n, len(sigs)))
        what = ('asm:' + asm[n]) if n in asm else ('absolute' if n in addr else 'missing')
        cat[what.split(':')[0]] += 1
        ret = CT.get(rs[0], 'int') if rs else 'void'
        args = ', '.join(f'{CT.get(t, "int")} a{i}' for i, t in enumerate(ps)) or 'void'
        body = f'port_stub_hit("{n}", "{what}");' + ('' if ret == 'void' else ' return 0;')
        L.append(f'__attribute__((weak)) {ret} {n}({args}) {{ {body} }}')
    open(f'{outdir}/asm_stubs.c', 'w').write('\n'.join(L) + '\n')

    # ---- data stubs: arrays sized by the gap to the next known N64 symbol address
    known = sorted(set(v for v in addr.values() if v >= 0x80000000))
    import bisect
    D = ['/* GENERATED by port/tools/gen_stubs.py - do not edit. Zeroed storage for data symbols that live in',
         ' * ROM blobs / absolute addresses on the N64 (Phase 2b will replace these with real data). */', '']
    lowabs = []
    total = 0
    for n in datas:
        a = addr.get(n)
        if a is None:
            m = re.match(r'D_([0-9A-F]{8})$', n)
            a = int(m[1], 16) if m else None
        size = 0x100
        if a is not None and a >= 0x80000000:
            i = bisect.bisect_right(known, a)
            size = (known[i] - a) if i < len(known) else 0x1000
            size = max(16, min(size, 0x100000))
        elif a is not None:
            lowabs.append((n, a))
        size = (size + 15) & ~15
        total += size
        D.append(f'__attribute__((weak, aligned(16))) unsigned char {n}[0x{size:X}];'
                 + (f' /* N64 0x{a:08X} */' if a is not None else ''))
    open(f'{outdir}/data_stubs.c', 'w').write('\n'.join(D) + '\n')

    with open(f'{outdir}/stubs_report.txt', 'w') as f:
        f.write(f'function stubs: {len(funcs)}  ' + ', '.join(f'{k}={v}' for k, v in cat.most_common()) + '\n')
        f.write(f'GLOBAL_ASM functions (asm-only) in source: {len(asm)}\n')
        f.write(f'data stubs: {len(datas)}  ({total/1048576:.1f} MB zeroed)\n')
        f.write(f'functions imported with conflicting signatures across TUs: {len(conflicts)}\n')
        for n, k in conflicts:
            sig = '; '.join(f'{",".join(p) or "void"}->{",".join(r) or "void"} x{c}' for (p, r), c in undef_f[n].items())
            f.write(f'  {n}: {sig}\n')
        f.write(f'data symbols with an absolute value below 0x80000000 (ROM offsets / sizes used as &sym): {len(lowabs)}\n')
        for n, a in lowabs[:40]:
            f.write(f'  {n} = 0x{a:X}\n')
    print(open(f'{outdir}/stubs_report.txt').read().split('\n', 4)[:4])


if __name__ == '__main__':
    main()
