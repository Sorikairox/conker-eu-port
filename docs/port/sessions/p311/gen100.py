def rec(d):
    b = bytearray(0x4C)
    b[0] = d['kind']; b[1] = d['owner']; b[0xC] = d['c']
    struct.pack_into('>HHHHHHHHHHHH', b, 0xE, d['px'] & 0xFFFF, d['py'] & 0xFFFF, d['pz'] & 0xFFFF, d['pa'] & 0xFFFF,
                     d['pb'] & 0xFFFF, d['rab'] & 0xFFFF, d['rb'] & 0xFFFF, d['rise'] & 0xFFFF, d['riser'], d['timer'], d['flags'], 0)
    b[0x24:0x2E] = bytes(d['parm']); b[0x2E:0x32] = bytes(d['col']); b[0x32:0x38] = bytes(d['parm2']); b[0x38:0x3C] = bytes(d['colr'])
    b[0x3C:0x49] = bytes([d['life'], d['sxz'], d['sy'], d['obj'], d['p40'], d['period'], d['cd'], d['chance'], d['count'],
                          d['spd'], d['off'], d['mtx'], d['p48']])
    pk = ['%08X=%08X' % (0x80480000 + i, struct.unpack_from('>I', b, i)[0]) for i in range(0, 0x4C, 4)]
    pk += ['800BEE04=%08X' % (d['delta'] & 0xFFFFFFFF), '800CCBF0=%08X' % d['m1d4'], '800CCA90=0000%04X' % d['ang'],
           '800CCA58=' + f(d['ospd'])]
    pk += d.get('extra', [])
    return ','.join(pk)
