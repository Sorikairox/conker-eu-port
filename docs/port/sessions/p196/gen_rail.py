def nodebytes(nodes):
    b = b''
    for x, y, z, l, t, bd in nodes:
        l = (l + [FF] * 5)[:5]
        b += struct.pack('>hhhBBB5BBB', x, y, z, 0xAA, 0xBB, 0xCC, *l, t, bd)
    return b
def words(base, b):
    b = b + b'\0' * (-len(b) % 4)
    return ['%08X=%08X' % (base + i, struct.unpack('>I', b[i:i + 4])[0]) for i in range(0, len(b), 4)]
