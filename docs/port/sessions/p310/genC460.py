# Args: 0 yaw f, 1 dist f, 2 rise f, 3 height f, 4 alpha u8, 5 mode, 6 floor_off f, 7 smooth f, 8 target, 9 flags, 10 snap.
import os, struct
def fb(x): return struct.unpack('>I', struct.pack('>f', x))[0]
BASE = 0x800CC6F0
def rec(i): return (BASE + i * 0x32C) & 0xFFFFFFFF
def setup(name, mode=4, count=0, ed=3, ee=7, target=None, mtx=False, fixed=0, floor=0.0, ny=-1, fa0=1, d9f0=(0x80461000, 0x80462000),
          w300=0, aimon=0, flags=0, snap=0, hit=0xFF, a630=(0x1234,), aimb=(0x87, 0x65), rf6f8=(250.0,), rnd=(0x12345,),
          yaw=37.5, dist=120.0, rise=-14.0, height=2.5, alpha=0x64, smooth=0.75, follow=8, player_y=40.0):
    a = {0: fb(yaw), 1: fb(dist), 2: fb(rise), 3: fb(height), 4: alpha, 5: mode & 0xFFFFFFFF, 6: fb(floor), 7: fb(smooth),
         8: 0x80450000 if target else 0, 9: flags, 10: snap}
    pk = {0x800D196C: 0x80420000, 0x800C42B0: fixed << 24, 0x800BEA34: aimon << 8, 0x80083330: fa0 & 0xFFFFFFFF,
          0x800C4298: 0x05000000, 0x80420078: 0x00001ABC, 0x80420014: fb(11.0), 0x80420018: fb(player_y),
          0x8042001C: fb(-33.0), 0x804201D4: 0x80440000 if mtx else 0, 0x80420220: follow << 8, 0x80420064: 0x00ABCD00}
    for i in range(25): pk[rec(i)] = 4 if i < count else 2
    # record 0 (D_800CC704 / 08 / 0C), hit record 6, followed record 8
    for r, vals in ((0, (5.0, 7.0, -9.0, 0.5)), (6, (100.0, 77.0, 20.0, 1.5)), (8, (-60.0, 15.0, 45.0, 2.25))):
        for k, v in enumerate(vals): pk[rec(r) + 0x14 + 4 * k] = fb(v)
        pk[rec(r) + 0x3C] = fb(12.0 + r)
        pk[rec(r) + 0x74] = 0x00002345 + r
    obj = rec(ed)
    pk[obj + 0x18] = fb(ny)
    pk[obj + 0x300] = w300
    if target:
        for k, v in enumerate(target): pk[0x80450000 + 4 * k] = fb(v)
    ret = {'1505F0E0': '%X' % ed if isinstance(ed, str) else '%X' % rec(ed), '1505F25C': '%X' % rec(ee),
           '1515D9F0': ';'.join('%X' % x for x in d9f0), '1515D9B0': '80463000', '1505A9B0': ';'.join('%X' % x for x in a630),
           '1505DE88': '%X' % hit, '150ADF00': ';'.join('%X' % x for x in rnd), '10003E90': '80470000', '15159140': '80464000'}
    retf = '1505AA78=%s,15048790=%08X' % (';'.join('%08X' % fb(x) for x in rf6f8), fb(0.6))
    outa = '151F0678=0:%s' % ';'.join('%08X' % fb(1.0 + 0.5 * k) for k in range(16))
    outw = '1505F25C=1:00000009,150A7E40=4:%08X/5:%08X/6:%08X,1505A504=3:%08X/4:%08X/5:%08X' % (
        fb(31.0), fb(62.0), fb(-93.0), fb(8.5), fb(-4.25), fb(3.125))
    outb = '1505DE88=1:%s' % ';'.join('%X' % b for b in aimb)
    return '%s ! %s ! %s ! %s ! %s ! %s ! %s ! %s' % (name, ','.join('%d=%X' % kv for kv in a.items()),
        ','.join('%08X=%08X' % kv for kv in sorted(pk.items())), ','.join('%s=%s' % kv for kv in ret.items()), retf, outa, outw, outb)
