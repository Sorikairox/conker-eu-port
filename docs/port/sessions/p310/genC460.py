# Globals (EU): D_800C42B0 800C42B0 (fixed-point matrices), D_800BE616 800BEA36 (aim search on), D_80082FA0 80083330
# (loop count - 1), D_800C3E78 800C4298, D_800CC704 / 800CC708 / 800CC70C = record 0 +0x14 / +0x18 / +0x1C.
# EU jal keys: func_1505EEB0 1505F25C (RET slot, OUTW 1), func_15060F28 150612D4, func_1505ED34 1505F0E0 (RET slot),
# guMtxL2F 151F0678 (OUTA 0 = 16 words), func_150A7E40 150A7E40 (OUTW 4 / 5 / 6), func_1515D9F0 1515D9F0 (RET),
