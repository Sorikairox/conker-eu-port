#!/usr/bin/env python3
# P295: writes s6ED8.txt (setups for func_151B6ED8, ribbon_trail_draw). trail 80450000, points 80451000 (0x1C each),
# camera 80452000 (func_15144B34 = jal 151450A4), vertices 80460000 (func_151D6310 OUTW 3), gfx 80470000 (the five
# state helpers 15143394 / 15143180 / 1513FA54 / 151430EC / 1514352C return it).
import os, struct
def fb(x): return struct.unpack('>I', struct.pack('>f', x))[0]
def setup(name, n=6, count=6, head=4, tail=1, bit=0, verts=0x80460000, cam=(0.0, 50.0, -300.0), pts=None, tpos=(5.0, 6.0, 7.0)):
    if pts is None:
        pts = [((10.0 * i + 0.5, 3.0 * i - 2.25, 100.0 - 7.0 * i * i), 0x20 * i + 3, 1.5 * i - 2.75) for i in range(count)]
    pk = {0x80450010: fb(tpos[0]), 0x80450014: fb(tpos[1]), 0x80450018: fb(tpos[2]), 0x8045001C: bit,
          0x80450024: count << 16, 0x8045002C: ((n & 0xFF) << 24) | ((tail & 0xFF) << 16) | ((head & 0xFF) << 8),
          0x80450094: 0x80451000}
    for i, (p, al, w) in enumerate(pts):
        base = 0x80451000 + 0x1C * i
        for j in range(3): pk[base + 4 * j] = fb(p[j])
        pk[base + 0x10] = al << 24; pk[base + 0x14] = fb(w)
    for j in range(3): pk[0x80452000 + 4 * j] = fb(cam[j])
    g = 0x80470000
    ret = '151450A4=80452000,15143394=%X,15143180=%X,1513FA54=%X,151430EC=%X,1514352C=%X' % (g, g, g, g, g)
    return '%s ! 0=80450000,1=80470000,2=%X ! %s ! %s ! ! ! 151D6310=3:%X !' % (
        name, 0x8001, ','.join('%08X=%08X' % kv for kv in sorted(pk.items())), ret, verts)
line = [((0.0, 50.0, -300.0 + 10.0 * i), 0x40, 1.0) for i in range(4)]
L = ['# P295 setups for func_151B6ED8 (ribbon_trail_draw), generated by gen6ED8.py']
L += [setup('base'), setup('n1', n=1), setup('n2', n=2, head=2, tail=0), setup('nov', verts=0), setup('own', bit=2),
      setup('own3', bit=3, head=0, tail=3), setup('h0', head=0, tail=2), setup('h1', head=1, tail=3), setup('wrap', head=2, tail=4),
      setup('nm', n=-1 & 0xFF), setup('line', count=4, head=3, tail=0, pts=line), setup('lineown', count=4, head=3, tail=0, pts=line, bit=2, tpos=(0.0, 50.0, -250.0)),
      setup('c8', count=8, head=5, tail=6), setup('passhead', head=4, tail=3)]
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 's6ED8.txt'), 'w').write('\n'.join(L) + '\n')
