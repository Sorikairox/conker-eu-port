#!/usr/bin/env python3
# P295: writes sCBF80.txt (setups for func_150CBF80, ground_puff_spawn). obj 80450000 (+0x1D4 matrices 80460000,
# +0x7A facing), record from func_1513D668 (jal 1513DBD8) at 80470000. EU jal keys: func_15143134 151436A4,
# func_15046F70 15046F70, func_1504715C 1504744C, func_150CD2A0 150CD2A0, func_150ADA20 150ADF00, func_150ADA68 150ADF48.
import os, struct
def fb(x): return '%08X' % struct.unpack('>I', struct.pack('>f', x))[0]
def setup(name, which=0, a2=0x1234, a3=0x80, obj=0x80450000, mtx=0x80460000, facing=0xA3C5, found=1, rec=0x80470000,
          rgb=(200.7, 99.2, 0.9), pos=(123.5, -40.25, 987.0), floor=-55.5, ri=(50, 0x10203, 7, 0x8001, 13),
          rf=(0.5, 0.25, 0.75, 0.125, 0.9)):
    pk = []
    if obj:
        pk += ['80450078=%08X' % facing, '804501D4=%08X' % mtx]
    hit = ';'.join([fb(floor)] + [fb(1.5 * k) for k in range(1, 9)])
    ret = '15046F70=%X,1513DBD8=%X,150ADF00=%s' % (found, rec, ';'.join('%X' % v for v in ri))
    retf = '150ADF48=' + ';'.join(fb(v) for v in rf)
    outa = '151436A4=1:%s,15046F70=3:%s,1504744C=0:%s' % (';'.join(fb(v) for v in pos), hit, ';'.join(fb(-2.0 * k) for k in range(9)))
    outw = '150CD2A0=1:%s/2:%s/3:%s' % tuple(fb(v) for v in rgb)
    return '%s ! 0=%08X,1=%X,2=%X,3=%X ! %s ! %s ! %s ! %s ! %s !' % (name, obj, which, a2, a3, ','.join(pk), ret, retf, outa, outw)
L = ['# P295 setups for func_150CBF80 (ground_puff_spawn), generated by genCBF80.py']
L += [setup('w0'), setup('w1', which=1), setup('w2', which=2), setup('nullobj', obj=0), setup('nomtx', mtx=0),
      setup('nofloor', found=0), setup('norec', rec=0), setup('w1b', which=1, a2=-5 & 0xFFFFFFFF, a3=0xFF, facing=0x00FF),
      setup('rhi', which=2, ri=(0xFFFFFFFF, 0xFFFFFFFE, 0xFFFFFFFD, 0xFFFFFFFC, 0xFFFFFFFB), rf=(0.0, 0.999, 0.0, 1.0, 0.3)),
      setup('rmod', which=0, ri=(50, 0x41, 6, 13, 27), rgb=(255.0, 254.99, 128.5)),
      setup('rmod2', which=1, ri=(51, 0x40, 7, 14, 28), rgb=(1.0, 0.0, 17.3)),
      setup('rmod3', which=2, ri=(101, 0x32, 8, 9, 41))]
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'sCBF80.txt'), 'w').write('\n'.join(L) + '\n')
