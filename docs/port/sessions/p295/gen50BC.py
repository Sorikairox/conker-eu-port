#!/usr/bin/env python3
# P295: writes s50BC.txt (setups for func_151C50BC, beam_hit_update). src record 80450000, hit 80451000, pos 80452000,
# dir 80452100, out 80452200, from 80452300, to 80452400, flags 80452500, caster 80453000; D_800DBEF4 (EU 800DC324)
# -> materials 80460000 (0xA0 each). EU jal keys: func_15145128 15145698, func_15081A90 15081A90 (OUTA 7 = the
# record it fills), func_150ACEA0 150ACEA0 (OUTW 12 = material index), func_151C2600 151C2600.
import os, struct
def fb(x): return struct.unpack('>I', struct.pack('>f', x))[0]
def rec(kind=2, dist=50.0, point=(10.0, 20.0, 30.0), start=(1.0, 2.0, 3.0), dirv=(0.5, -0.25, 0.75), mat=0x80460140, extra=0x1234):
    w = [0x80455000, fb(dist)] + [fb(v) for v in point] + [fb(0.1 * k) for k in range(6)] + [fb(v) for v in start] + [fb(v) for v in dirv]
    w += [0x44000000 + k for k in range(5)] + [0x11000000 | (kind << 16) | 0x2233, mat, extra]
    assert len(w) == 25
    return w
POS = (1.0, 2.0, 3.0)
def setup(name, src=None, cast=1, dirp=1, fromp=0, top=0, objects=1, models=1, filt=-3, recheck=0, n28=1, ra=None,
          ace=1, mat=None, hitrec=None, pos=POS, scale=1.5, miss=-7.25, mask=0x0C, flags=0x5F):
    a = {0: 0x80450000 if src is not None else 0, 1: 0x80451000, 2: 0x80452000, 3: 0x80452100 if dirp else 0,
         4: 0x80452200, 5: fb(scale), 6: cast, 7: 0x80452300 if fromp else 0, 8: 0x80452400 if top else 0,
         9: 0x80452500, 10: mask, 11: fb(miss), 12: 0x80453000, 13: filt & 0xFFFFFFFF, 14: objects, 15: models,
         16: 0x1F0, 17: recheck}
    pk = {0x800DC324: 0x80460000, 0x80452500: flags << 24}
    for i, v in enumerate(pos): pk[0x80452000 + 4 * i] = fb(v)
    for i, v in enumerate((0.0, -1.0, 0.5)): pk[0x80452100 + 4 * i] = fb(v)
    for i, v in enumerate((4.0, 5.0, 6.0)): pk[0x80452300 + 4 * i] = fb(v)
    for i, v in enumerate((0.25, 0.5, -0.75)): pk[0x80452400 + 4 * i] = fb(v)
    if src is not None:
        for i, v in enumerate(src): pk[0x80450000 + 4 * i] = v
    hr = hitrec if hitrec is not None else rec()
    for i, v in enumerate(rec(kind=0, mat=0)): pk[0x80451000 + 4 * i] = v
    ret = '15145698=%s,150ACEA0=%X' % (';'.join('%X' % x for x in (n28 if isinstance(n28, tuple) else (n28,))), ace)
    outa = '15081A90=7:' + ';'.join('%08X' % v for v in hr)
    outw = '150ACEA0=12:%X' % (mat & 0xFFFFFFFF) if mat is not None else ''
    args = ','.join('%d=%X' % (k, v) for k, v in a.items())
    return '%s ! %s ! %s ! %s ! ! %s ! %s !' % (name, args, ','.join('%08X=%08X' % kv for kv in sorted(pk.items())), ret, outa, outw)
L = ['# P295 setups for func_151C50BC (beam_hit_update), generated by gen50BC.py']
L += [setup('s_same', src=rec(start=POS)), setup('s_move', src=rec(start=(1.0, 2.0, 3.5))),
      setup('s_move0', src=rec(start=(9.0, 2.0, 3.0)), n28=0), setup('s_movey', src=rec(start=(1.0, 2.5, 3.0))),
      setup('s_re2', src=rec(start=POS, kind=2), recheck=1, hitrec=rec(kind=1, dist=9.0)),
      setup('s_re3', src=rec(start=POS, kind=3), recheck=1, hitrec=rec(kind=3, dist=8.0)),
      setup('s_re3miss', src=rec(start=POS, kind=3), recheck=1, hitrec=rec(kind=0, dist=8.0)),
      setup('s_re1', src=rec(start=POS, kind=1), recheck=1, hitrec=rec(kind=2, dist=7.0)),
      setup('s_re2off', src=rec(start=POS, kind=2), recheck=0, hitrec=rec(kind=1, dist=9.0)),
      setup('nc_dir', cast=0), setup('nc_to', cast=0, dirp=0, top=1), setup('nc_none', cast=0, dirp=0),
      setup('nc_both', cast=0, dirp=1, top=1), setup('nc_100', cast=0x100, dirp=0),
      setup('c_k0', hitrec=rec(kind=0)), setup('c_k0to', hitrec=rec(kind=0), dirp=0, top=1),
      setup('c_k0none', hitrec=rec(kind=0), dirp=0, top=0),
      setup('c_k1', hitrec=rec(kind=1, start=POS)), setup('c_k1mv', hitrec=rec(kind=1, start=(1.0, 2.0, 4.0))),
      setup('c_k1mv0', hitrec=rec(kind=1, start=(1.0, 2.0, 4.0)), n28=0), setup('c_k1nm', hitrec=rec(kind=1, start=POS, mat=0)),
      setup('c_k2ace', hitrec=rec(kind=2, start=POS), ace=1, mat=3), setup('c_k2ace0', hitrec=rec(kind=2), ace=0),
      setup('c_k2ace100', hitrec=rec(kind=2), ace=0x100), setup('c_k3m1', hitrec=rec(kind=3, start=POS), ace=1, mat=-1),
      setup('ft_k1', fromp=1, top=1, hitrec=rec(kind=1, start=(4.0, 5.0, 6.0))),
      setup('ft_k2', fromp=1, top=1, hitrec=rec(kind=2, start=(4.0, 5.0, 6.0)), ace=1, mat=5),
      setup('ft_k2n0', fromp=1, top=1, hitrec=rec(kind=2), n28=0), setup('ft_k2a0', fromp=1, top=1, hitrec=rec(kind=2), ace=0),
      setup('ft_k3mv', fromp=1, top=1, hitrec=rec(kind=3), ace=1, n28=(1, 0)),
      setup('f_only', fromp=1, top=0, hitrec=rec(kind=2), ace=1), setup('t_only', fromp=0, top=1, hitrec=rec(kind=3, start=POS), ace=1),
      setup('obj0', objects=0, models=1, hitrec=rec(kind=1)), setup('mod0', objects=1, models=0, hitrec=rec(kind=1)),
      setup('obj100', objects=0x100, models=0x100, hitrec=rec(kind=1), filt=0x1FF),
      setup('re100', src=rec(start=POS, kind=2), recheck=0x100, hitrec=rec(kind=1))]
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 's50BC.txt'), 'w').write('\n'.join(L) + '\n')
