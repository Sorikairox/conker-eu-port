#!/usr/bin/env python3
# P301: writes s334Cb.txt: P282's s334C setups again with DIFFTEST_OUTA on memcpy (EU 10023360) writing p+0x38..0x40
# (100, 50, -20) into old[]: memcpy is a difftest stub, so in s334C old[] stayed STKFILL garbage (A5A5A5A5 on both
# sides) and the handler argument swaps old[1] <-> old[2] / old[0] <-> old[1] could not show. Plus `len1*` setups with
# velocity (1, 0, 0) (|v| == 1.0 exactly) for the `1.0f < len` boundary. Names get an `o` suffix.
import os, struct
D = os.path.dirname(os.path.abspath(__file__))
OLD = '10023360=0:42C80000;42480000;C1A00000'
src = open(os.path.join(D, '..', 'p282', 'gen334C.py')).read().split("L = ['#")[0]
g = {'__file__': os.path.join(D, '..', 'p282', 'gen334C.py')}
exec(src, g)
def withold(line, name):
    f = line.split('!')
    f[0] = name + ' '
    f[5] = ' ' + OLD + ' '
    return '!'.join(f)
L = ['# P301 setups for func_1513334C with memcpy OUTA (old[] = 100, 50, -20), generated by gen334Cb.py']
for ln in open(os.path.join(D, '..', 'p282', 's334C.txt')):
    if ln.startswith('#') or not ln.strip(): continue
    L.append(withold(ln.rstrip('\n'), ln.split('!')[0].strip() + 'o'))
S = g['setup']
for nm, fl, typ in (('len1a', 0x17, 1), ('len1b', 0x15, 0), ('len1c', 0x17, 3)):
    L.append(withold(S(nm, fl, typ=typ, vel=(1.0, 0.0, 0.0)), nm))
# D_80089CD4[6] (15133F44) is reached only with type 1 / 2 (P282's t73_6 uses type 3)
L += [withold(S('t73_6t1', 0x7F, t73=6, typ=1, t75=3), 't73_6t1'), withold(S('t73_6t1z', 0x7F, t73=6, typ=1, h1=0), 't73_6t1z')]
open(os.path.join(D, 's334Cb.txt'), 'w').write('\n'.join(L) + '\n')
