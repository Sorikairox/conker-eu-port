# P301: writes s3CB8.txt (setups for func_150E3CB8, zap_bolt_update). obj 80410000 (+0x10 pos, +0x1C target, +0x28
# anchor, +0x34 speed, +0x3C followed object, +0x40, +0x44 timer, +0x4C / +0x50 accumulators, +0x54 ground, +0x58 style,
# +0x6C, +0x71 kind, +0x74, +0x78 path, +0x7C s16 life), followed object 80420000, path 80430000.
# Globals (EU): D_800BE9E4 frames 800BEE04, D_800BE9A4 dt 800BEDC4. EU jal keys: func_150ADA68 150ADF48 (RETF),
# func_150ADA20 150ADF00, func_15143874 15143DE4 (OUTW 2 / 3 = x / z offset), func_15046F70 15046F70 (RET = ground
# hit), func_15145128 15145698 (RET, OUTW 2 = length), func_151C284C 151C284C (RET = hit), func_150E3A94 150E3A94.
import os, struct
def fb(x): return struct.unpack('>I', struct.pack('>f', x))[0]
def setup(name, life=100, follow=None, fword=1, path=None, timer=0, pos=(10.0, 20.0, 30.0), target=(40.0, 60.0, 90.0),
          speed=3.0, frames=2, dt=0.5, acc=(2.5, 1.5), kind=1, ground=1, norm=1, hits=(0,), rf=None, ri=None):
    a = {0: 0x80410000}
    pk = {0x800BEE04: frames, 0x800BEDC4: fb(dt), 0x8041007C: (life & 0xFFFF) << 16 | 0x1234,
          0x8041003C: 0x80420000 if follow else 0, 0x80410078: 0x80430000 if path else 0, 0x80410044: timer & 0xFFFFFFFF,
          0x80410034: fb(speed), 0x8041004C: fb(acc[0]), 0x80410050: fb(acc[1]), 0x80410054: fb(-12.5), 0x80410040: 0x4567,
          0x8041006C: 0x89AB, 0x80410070: 0x00000000 | (kind << 16), 0x80410074: 0x80444000, 0x8041000C: 0x05000000,
          0x80410000: 0x00270000}
    for i, v in enumerate(pos): pk[0x80410010 + 4 * i] = fb(v)
    for i, v in enumerate(target): pk[0x8041001C + 4 * i] = fb(v)
    for i, v in enumerate((-3.0, 7.5, 11.25)): pk[0x80410028 + 4 * i] = fb(v)
    for i in range(5): pk[0x80410058 + 4 * i] = 0x11223344 + i * 0x01010101
    if follow:
        pk[0x80420000] = fword
        for i, v in enumerate(follow): pk[0x80420014 + 4 * i] = fb(v)
    if path:
        for i, v in enumerate(path): pk[0x80430000 + 4 * i] = fb(v)
    rf = rf or [0.3, 0.2, 0.7, 0.45, 0.6, 0.15, 0.55, 0.9, 0.35, 0.8, 0.25, 0.65]
    ri = ri or [0x12345, 0x6789B, 0xABCDF, 0x13579, 0x2468A, 0x7FFF3]
    ret = '150ADF00=%s,15046F70=%X,15145698=%X,151C284C=%s' % (';'.join('%X' % x for x in ri), ground, norm, ';'.join('%X' % h for h in hits))
    outw = '15143DE4=2:%08X;%08X/3:%08X;%08X,15145698=2:%08X;%08X' % (fb(4.5), fb(-6.25), fb(-2.75), fb(8.5), fb(123.0), fb(77.5))
    args = ','.join('%d=%X' % kv for kv in a.items())
    return '%s ! %s ! %s ! %s ! 150ADF48=%s ! ! %s !' % (name, args, ','.join('%08X=%08X' % kv for kv in sorted(pk.items())), ret,
        ';'.join('%08X' % fb(v) for v in rf), outw)
L = ['# P301 setups for func_150E3CB8 (zap_bolt_update), generated by gen3CB8.py']
