      setup('stepeqf', pos=(0.0, 0.0, 0.0), target=(3.0, 4.0, 0.0), speed=2.5, follow=(3.0, 4.0, 0.0)),
      setup('stepgt', pos=(0.0, 0.0, 0.0), target=(3.0, 4.0, 0.0), speed=2.4),
