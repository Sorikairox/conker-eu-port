#!/usr/bin/env python3
# P301: writes s4BF0.txt (setups for func_150B4BF0, beam_ribbon_draw). trail 80450000, points 80451000 (0x24 each:
# pos, +0x18 width, +0x1C u16 fade, +0x20 u8 s), style 80453000 (+0x1C flags, +0x24 grey, +0x26 s16 alpha scale,
# +0x32..+0x35 ramp counts / steps), camera = D_800DBFF0 (EU 800DC420) 80440000 + arg2 (1) * 0x9A0 + 0x2F8,
# vertices 80460000 (func_151D6310 OUTW 3), gfx 80470000 (the five state helpers 15143394 / 151430EC / 1513FA54 /
# 15143180 / 1514352C return it). memcpy = 10023360 (stub: ARGMEM on its source).
import os, struct
def fb(x): return struct.unpack('>I', struct.pack('>f', x))[0]
CAM = 0x80440000 + 0x9A0 + 0x2F8
def setup(name, n=6, count=6, head=4, tail=1, bit=0, verts=0x80460000, cam=(0.0, 50.0, -300.0), pts=None,
          tpos=(5.0, 6.0, 7.0), flags=0, grey=0x9C, scale=0x1A0, ramp=(3, 0x21, 2, 0x13), svals=None, wmul=1.0):
    if pts is None:
        sv = svals or [0x10, 0x30, 0x20, 0x28, 0x08, 0x40, 0x18, 0x50]
        pts = [((10.0 * i + 0.5, 3.0 * i - 2.25, 100.0 - 7.0 * i * i), 0x100 * i + 0x37, sv[i], (1.5 * i + 2.75) * wmul) for i in range(count)]
    pk = {0x80450010: fb(tpos[0]), 0x80450014: fb(tpos[1]), 0x80450018: fb(tpos[2]), 0x8045001C: bit,
          0x80450024: count << 16, 0x8045002C: ((n & 0xFF) << 24) | ((tail & 0xFF) << 16) | ((head & 0xFF) << 8),
          0x80450094: 0x80451000, 0x80450098: 0x80453000, 0x800DC420: 0x80440000,
          0x8045301C: flags << 24, 0x80453024: (grey << 24) | (scale & 0xFFFF),
          0x80453030: (ramp[0] << 8) | ramp[1], 0x80453034: (ramp[2] << 24) | (ramp[3] << 16)}
    for i, (p, fade, s, w) in enumerate(pts):
        base = 0x80451000 + 0x24 * i
        for j in range(3): pk[base + 4 * j] = fb(p[j])
        pk[base + 0x18] = fb(w); pk[base + 0x1C] = fade << 16 | 0x5A5A; pk[base + 0x20] = s << 24 | 0x123456
    for j in range(3): pk[CAM + 4 * j] = fb(cam[j])
    g = 0x80470000
    ret = '15143394=%X,15143180=%X,1513FA54=%X,151430EC=%X,1514352C=%X' % (g, g, g, g, g)
    return '%s ! 0=80450000,1=80470000,2=1 ! %s ! %s ! ! ! 151D6310=3:%X !' % (
        name, ','.join('%08X=%08X' % kv for kv in sorted(pk.items())), ret, verts)
line = [((0.0, 50.0, -300.0 + 10.0 * i), 0x40, 0x10 * i, 1.0) for i in range(4)]
L = ['# P301 setups for func_150B4BF0 (beam_ribbon_draw), generated by gen4BF0.py']
L += [setup('base'), setup('n1', n=1), setup('n2', n=2, head=2, tail=0), setup('nov', verts=0), setup('own', bit=2),
      setup('own3', bit=3, head=0, tail=3), setup('h0', head=0, tail=2), setup('h1', head=1, tail=3), setup('wrap', head=2, tail=4),
      setup('nm', n=-1 & 0xFF), setup('line', count=4, head=3, tail=0, pts=line),
      setup('lineown', count=4, head=3, tail=0, pts=line, bit=2, tpos=(0.0, 50.0, -250.0)),
      setup('c8', count=8, head=5, tail=6), setup('passhead', head=4, tail=3),
      setup('f2', flags=2), setup('f4', flags=4), setup('f6', flags=6, ramp=(10, 0x51, 10, 0x61)),
      setup('f6z', flags=6, ramp=(0, 0x45, 0, 0x29)), setup('f2h0', flags=2, head=0, tail=4, ramp=(4, 0x90, 1, 1)),
      setup('f4h0', flags=4, head=0, tail=2, ramp=(1, 1, 4, 0x90)), setup('f3', flags=3, ramp=(2, 0x70, 2, 0x70)),
      setup('neg', scale=-0x2C0, grey=0x11), setup('sdesc', svals=[0x50, 0x40, 0x30, 0x20, 0x10, 0x08, 0x04, 0x02]),
      setup('sasc', svals=[0x02, 0x04, 0x08, 0x10, 0x20, 0x30, 0x40, 0x50]), setup('seq', svals=[0x20] * 8),
      setup('sascown', svals=[0x02, 0x04, 0x08, 0x10, 0x20, 0x30, 0x40, 0x50], bit=2),
      setup('sdescown', svals=[0x50, 0x40, 0x30, 0x20, 0x10, 0x08, 0x04, 0x02], bit=2, head=0, tail=3)]
L += [setup('wide', wmul=97.0), setup('wideown', wmul=211.0, bit=2), setup('sstep1', svals=[0x30, 0x2F, 0x2E, 0x2D, 0x2C, 0x2B, 0x2A, 0x29]),
      setup('sstep1w', svals=[0x30, 0x2F, 0x2E, 0x2D, 0x2C, 0x2B, 0x2A, 0x29], wmul=50.0, head=0, tail=3)]
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 's4BF0.txt'), 'w').write('\n'.join(L) + '\n')
