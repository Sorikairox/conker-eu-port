#!/usr/bin/env python3
# P301: writes s40BC.txt (setups for func_151C40BC, impact_effects_spawn). obj 80410000 (+0x140 pos, +0x170 prev,
# +0x198 surface bits, +0xC room, +1 owner). D_800BE9F0 (level) EU 800BEE10, D_800BE616 EU byte 800BEA36.
# EU jal keys: func_150ADA68 150ADF48 (RETF = the random floats in call order), func_150ADA20 150ADF00 (RET).
# Random float order: [spark cmp, spark scale] [smoke cmp, grow, size] [debris cmp] [flash cmp].
import os, struct
def fb(x): return struct.unpack('>I', struct.pack('>f', x))[0]
RND = (0x12345, 0x6789B, 0xABCDF, 0x13579, 0x2468A, 0x7FFF3, 0x55554, 0x31337)
def setup(name, level=0x2B, surface=0, hd=0, ch=(0.5, 0.5, 0.5, 0.5), take=(1, 1, 1, 1), eq=None, rnd=RND, tags=(0x11, 0x22, 0x33)):
    seq = []
    for k, t in enumerate(take):
        c = 0.25 if t else 0.75
        if eq == k: c = ch[k]
        seq.append(c)
        if t and k == 0: seq.append(0.375)
        if t and k == 1: seq += [0.625, 0.8125]
    a = {0: 0x80410000, 1: fb(ch[0]), 2: fb(ch[1]), 3: fb(ch[2]), 4: fb(ch[3]), 5: tags[0], 6: tags[1], 7: tags[2]}
    pk = {0x800BEE10: level, 0x800BEA34: hd << 8, 0x80410198: 0xFFFFFF00 | surface, 0x8041000C: 0x07000000,
          0x80410000: 0x00090000}
    for i, v in enumerate((10.5, -20.25, 30.75)): pk[0x80410140 + 4 * i] = fb(v)
    for i, v in enumerate((1.0, 2.5, -3.0)): pk[0x80410170 + 4 * i] = fb(v)
    args = ','.join('%d=%X' % kv for kv in a.items())
    return '%s ! %s ! %s ! 150ADF00=%s ! 150ADF48=%s ! ! !' % (name, args, ','.join('%08X=%08X' % kv for kv in sorted(pk.items())),
        ';'.join('%X' % r for r in rnd), ';'.join('%08X' % fb(v) for v in seq))
L = ['# P301 setups for func_151C40BC (impact_effects_spawn), generated by gen40BC.py']
for nm, lv, sf in (('t4a', 0x2B, 0), ('t3a', 0x30, 1), ('t4b', 0x2B, 5), ('t4c', 0x30, 7), ('t1', 4, 0xB), ('t0a', 4, 0xA),
                   ('t2a', 0xE, 1), ('t2b', 0xE, 0xA), ('t0b', 0xE, 0xB), ('t3b', 0x34, 2), ('t5', 0x27, 0), ('t0c', 0x10, 1),
                   ('t0d', 0x2C, 0)):
    L.append(setup(nm, lv, sf))
    L.append(setup(nm + 'h', lv, sf, hd=3, rnd=RND[1:] + RND[:1]))
for k in range(4):
    L.append(setup('skip%d' % k, take=tuple(int(j != k) for j in range(4))))
    L.append(setup('eq%d' % k, take=tuple(int(j != k) for j in range(4)), eq=k))
L.append(setup('none', take=(0, 0, 0, 0)))
L.append(setup('flash1', rnd=(0x12345, 0x6789A, 0xABCDF)))
L.append(setup('flash1t5', level=0x27, rnd=(0x12345, 0x6789A, 0xABCDF)))
L.append(setup('t0chance', level=0x10, take=(1, 1, 1, 1)))
L.append(setup('lowch', ch=(0.3, 0.3, 0.3, 0.3)))
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 's40BC.txt'), 'w').write('\n'.join(L) + '\n')
